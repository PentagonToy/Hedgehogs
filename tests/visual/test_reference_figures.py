"""Opt-in environment-specific image comparisons with failure diff images."""
from hashlib import sha256
import json
from pathlib import Path

from matplotlib.testing.compare import compare_images
from PIL import Image
import pytest

from .cases import CASES, environment, environment_key, render


def assert_reference(expected, actual):
    result = compare_images(str(expected), str(actual), tol=.5, in_decorator=True)
    assert result is None, f'Visual regression: {result}'


@pytest.mark.visual
@pytest.mark.parametrize('name', CASES)
def test_reference_figure(name, tmp_path, request):
    configured = request.config.getoption('--visual-baseline-dir')
    root = Path(configured) if configured else Path(__file__).parent / 'baseline_images'
    baseline = root / environment_key()
    assert (baseline / 'metadata.json').is_file(), (
        f'No visual baseline for {environment_key()}. Render references with '
        'tools/render_visual_regressions.py, inspect them, then select their parent '
        'with --visual-baseline-dir. References are never regenerated by tests.')
    metadata = json.loads((baseline / 'metadata.json').read_text())
    assert metadata['environment'] == environment()
    expected = baseline / f'{name}.png'
    assert sha256(expected.read_bytes()).hexdigest() == metadata['images'][name]
    actual = tmp_path / f'{name}.png'
    render(name, actual)
    assert_reference(expected, actual)


def test_image_comparison_detects_a_changed_result(tmp_path):
    expected, actual = tmp_path / 'expected.png', tmp_path / 'actual.png'
    image = Image.new('RGB', (32, 32), 'white')
    image.save(expected)
    image.save(actual)
    assert_reference(expected, actual)
    image.paste('black', (0, 0, 16, 32))
    image.save(actual)
    with pytest.raises(AssertionError, match='Visual regression'):
        assert_reference(expected, actual)
    assert (tmp_path / 'actual-failed-diff.png').is_file()
